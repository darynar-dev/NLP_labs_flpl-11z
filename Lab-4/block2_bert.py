import numpy as np
import torch
import spacy
from transformers import AutoTokenizer, AutoModel, pipeline


# ------------------------------------------------------------
# Частина А: self-attention "з нуля" (код з методички)
# ------------------------------------------------------------
def softmax(x):
    e = np.exp(x - np.max(x))
    return e / e.sum()


def self_attention(X):
    scores = X @ X.T  # хто на кого дивиться (скалярні добутки всіх пар слів)
    weights = np.array([softmax(r) for r in scores])  # кожен рядок -> ймовірності
    return weights @ X, weights  # контекстні вектори + матриця уваги


# Завдання 6. Self-attention для власного речення (5 слів, іграшкові вектори)
def task6_attention():
    print("=== Завдання 6. Матриця уваги ===")
    words = ['коса', 'лежала', 'на', 'свіжій', 'траві']
    # 3 виміри вигадані вручну: [предмет, дія, природа]
    X = np.array([
        [0.8, 0.1, 0.5],  # коса   - предмет, пов'язаний з природою (знаряддя)
        [0.1, 0.9, 0.1],  # лежала - дія
        [0.1, 0.1, 0.1],  # на     - службове слово, майже "порожній" вектор
        [0.2, 0.1, 0.7],  # свіжій - ознака, природа
        [0.3, 0.1, 0.9],  # траві  - природа
    ])
    context, weights = self_attention(X)

    # друкуємо матрицю з підписами рядків і стовпців
    print(" " * 8, end="")
    for w in words:
        print(f"{w:>8}", end="")
    print()
    for i, w in enumerate(words):
        print(f"{w:8}", end="")
        for j in range(len(words)):
            print(f"{weights[i][j]:8.2f}", end="")
        print()
    # Отриманий результат:
    #            коса  лежала      на  свіжій   траві
    # коса       0.29    0.15    0.13    0.20    0.24
    # лежала     0.18    0.32    0.16    0.17    0.17
    # на         0.21    0.20    0.19    0.20    0.21
    # свіжій     0.22    0.16    0.14    0.22    0.26
    # траві      0.23    0.14    0.13    0.23    0.28
    # Аналіз: 'коса' найбільше дивиться на себе (0.29) і на 'траві' (0.24) -
    # саме 'траві' підказує, що це знаряддя, а не зачіска.
    # 'на' має майже рівні ваги (~0.2) - службове слово не несе змісту.
    # 'свіжій' і 'траві' дивляться одне на одне - вони утворюють словосполучення.
    print("------------------------\n")


# ------------------------------------------------------------
# Частина Б: контекстні вектори через BERT (LiBERTa)
# trust_remote_code=True потрібен, бо в моделі власний токенізатор
# (так написано на сторінці моделі; без цього параметра буде помилка)
# ------------------------------------------------------------
tok = AutoTokenizer.from_pretrained('Goader/liberta-large-v2', trust_remote_code=True)
model = AutoModel.from_pretrained('Goader/liberta-large-v2')


def word_vector(sentence, word):
    # Повертає контекстний вектор слова, яке стоїть ПЕРШИМ у реченні.
    # Відмінність від методички: токенізатор може розбити слово на кілька
    # частин (subword), тому беремо середнє всіх його частин.
    # Позиція 0 - службовий токен початку речення, тому слово починається з позиції 1.
    inputs = tok(sentence, return_tensors='pt')
    with torch.no_grad():
        out = model(**inputs)
    n = len(tok.tokenize(word))  # на скільки частин розбито слово
    return out.last_hidden_state[0, 1:1 + n].mean(dim=0)


# Завдання 1–3. Омоніми: різні значення vs однакові значення
def tasks_1_3_homonyms():
    print("=== Завдання 1-3. Омоніми в BERT ===")
    # для кожного слова: 2 речення з ОДНАКОВИМ значенням + 1 з ІНШИМ значенням
    # омонім стоїть першим словом (з малої літери), щоб він токенізувався однаково
    data = {
        'коса': [
            'коса дівчини була довга й густа',       # зачіска
            'коса сестри сягала аж до пояса',        # зачіска
            'коса легко косила високу траву',        # знаряддя
        ],
        'ключ': [
            'ключ від квартири загубився в кишені',  # від замка
            'ключ від машини лежав на столі',        # від замка
            'ключ бив з-під скелі чистою водою',     # джерело
        ],
        'лист': [
            'лист від бабусі прийшов поштою',        # письмо
            'лист від друга я прочитав увечері',     # письмо
            'лист клена пожовтів і впав на землю',   # листок дерева
        ],
    }

    print(f"{'Слово':6} | {'cos (однакові)':15} | {'cos (різні)':12} | Розрізнив?")
    for word, sentences in data.items():
        # подивитися, як токенізатор розбив перше речення:
        print("   токени:", tok.tokenize(sentences[0]))

        v_same1 = word_vector(sentences[0], word)
        v_same2 = word_vector(sentences[1], word)
        v_other = word_vector(sentences[2], word)

        cos_same = torch.cosine_similarity(v_same1, v_same2, dim=0).item()
        cos_diff = torch.cosine_similarity(v_same1, v_other, dim=0).item()

        # BERT розрізнив значення, якщо для різних значень косинус менший
        if cos_diff < cos_same:
            result = "так"
        else:
            result = "ні"
        print(f"{word:6} | {cos_same:15.3f} | {cos_diff:12.3f} | {result}")
    print("Для порівняння: Word2Vec/FastText дали б 1.000 в усіх випадках (один вектор на слово)")
    print("------------------------\n")


