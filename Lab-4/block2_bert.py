# Завдання 4. NER для 3 речень
def task4_ner():
    print("=== Завдання 4. NER ===")
    nlp = spacy.load('uk_core_news_sm')

    # речення + сутності, які ми очікуємо побачити (перевірено вручну)
    sentences = [
        ('Тарас Шевченко навчався в Петербурзькій академії мистецтв.',
         [('Тарас Шевченко', 'PER'), ('Петербурзькій академії мистецтв', 'ORG')]),
        ('Національний банк України відкрив нове відділення у Львові.',
         [('Національний банк України', 'ORG'), ('Львові', 'LOC')]),
        ('Ліна Костенко народилася в Ржищеві на Київщині.',
         [('Ліна Костенко', 'PER'), ('Ржищеві', 'LOC'), ('Київщині', 'LOC')]),
    ]

    for text, expected in sentences:
        doc = nlp(text)
        found = [(ent.text, ent.label_) for ent in doc.ents]
        print(text)
        print("   модель знайшла:", found)
        for ent in expected:
            if ent in found:
                print(f"   {ent} - правильно")
            else:
                print(f"   {ent} - пропущено або неточні межі")
    print("------------------------\n")


# Завдання 5. Fill-mask: 5 речень, топ-3 передбачення
def task5_fill_mask():
    print("=== Завдання 5. Fill-mask ===")
    fill = pipeline('fill-mask', model='Goader/liberta-large-v2', trust_remote_code=True)
    sentences = [
        'Львів - найбільше місто на заході <mask>.',
        'Взимку діти люблять кататися на <mask>.',
        'Наприкінці семестру студенти складають <mask>.',
        'Найдовша річка України - <mask>.',
        'Я п\'ю каву з молоком і <mask>.',
    ]
    for s in sentences:
        predictions = fill(s, top_k=3)
        print(s)
        for p in predictions:
            print(f"   {p['token_str']:15} {p['score']:.3f}")
    print("------------------------\n")


